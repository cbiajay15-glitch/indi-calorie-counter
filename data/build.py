"""Build ../foods.js from recipes.py + USDA FoodData Central values.

Usage:
  python3 build.py <usda100.json>   # refresh ingredient values from a USDA extract, then build
  python3 build.py                  # build from the saved ingredient_values.json

usda100.json maps "sr:<fdc_id>" / "fd:<fdc_id>" -> {"name", "kcal", "p", "f", "c"} per 100 g.
"""
import datetime, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from ingredients import INGREDIENTS, DERIVED  # noqa: E402
from recipes import R  # noqa: E402

VALUES = os.path.join(HERE, "ingredient_values.json")
FIELDS = ("kcal", "p", "c", "f")


def refresh(usda_path):
    usda = json.load(open(usda_path, encoding="utf-8"))
    out = {}
    for key, spec in INGREDIENTS.items():
        fid = spec[0]
        if fid not in usda:
            sys.exit(f"missing USDA id {fid} for {key}")
        u = usda[fid]
        out[key] = {"label": spec[1], "usda_id": fid, "usda_name": u["name"],
                    "note": spec[2] if len(spec) > 2 else "",
                    **{k: round(u[k], 3) for k in FIELDS}}
    for key, (parts, label, note) in DERIVED.items():
        vals = {k: round(sum(out[i][k] * m for i, m in parts.items()), 3) for k in FIELDS}
        out[key] = {"label": label, "usda_id": "", "usda_name": "", "note": note, **vals}
    json.dump(out, open(VALUES, "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    print(f"saved {len(out)} ingredient values")


def parse(spec):
    items = {}
    for tok in spec.split():
        k, g = tok.split(":")
        items[k] = items.get(k, 0) + float(g)
    return items


def build():
    vals = json.load(open(VALUES, encoding="utf-8"))
    rows, names, warnings = [], set(), []
    for name, aliases, cat, serving, spec in R:
        if name in names:
            sys.exit(f"duplicate dish {name}")
        names.add(name)
        items = parse(spec)
        tot = dict.fromkeys(FIELDS, 0.0)
        for k, g in items.items():
            if k not in vals:
                sys.exit(f"{name}: unknown ingredient {k}")
            for f in FIELDS:
                tot[f] += vals[k][f] * g / 100
        # sanity: energy should be close to 4/4/9 Atwater from the macros
        atw = 4 * tot["p"] + 4 * tot["c"] + 9 * tot["f"]
        if tot["kcal"] > 20 and abs(atw - tot["kcal"]) / tot["kcal"] > 0.15:
            warnings.append(f"{name}: kcal {tot['kcal']:.0f} vs macros {atw:.0f}")
        recipe = ", ".join(f"{vals[k]['label']} {g:g} g" for k, g in items.items())
        rows.append([name, aliases, serving, round(tot["kcal"]), round(tot["p"], 1), round(tot["c"], 1),
                     round(tot["f"], 1), cat, recipe])
    header = (
        "// Indi Calorie Counter - food list. GENERATED by data/build.py, do not edit by hand.\n"
        "// Values are calculated from our own per-serving recipes (data/recipes.py) using ingredient values\n"
        "// from USDA FoodData Central (SR Legacy 2018-04 and Foundation Foods 2025-04), which is public domain (CC0).\n"
        "// Some Indian ingredients have no exact USDA entry; the closest equivalent is used (see data/ingredients.py).\n"
        "// Format: [name, aliases, serving, kcal, protein g, carbs g, fat g, category, recipe per serving]\n"
    )
    # Version = UTC build time (YYYYMMDDHHMM). Apps compare it to decide whether a downloaded list is newer.
    version = int(datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d%H%M"))
    body = ("window.INDI_FOODS_VERSION = " + str(version) + ";\n"
            "window.INDI_FOODS = [\n" + ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in rows) + "\n];\n")
    open(os.path.join(HERE, "..", "foods.js"), "w", encoding="utf-8").write(header + body)
    # foods.json: the same list as plain data, downloaded by installed apps to update their food list.
    with open(os.path.join(HERE, "..", "foods.json"), "w", encoding="utf-8") as fh:
        json.dump({"version": version, "count": len(rows), "foods": rows}, fh, ensure_ascii=False, separators=(",", ":"))
    print(f"built {len(rows)} dishes")
    for w in warnings:
        print("WARN", w)


if __name__ == "__main__":
    if len(sys.argv) > 1:
        refresh(sys.argv[1])
    build()
